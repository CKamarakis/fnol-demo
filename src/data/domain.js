/* --- Perishability model. This ordering is the organising principle
   of the whole form and it is MY recommendation, not an industry
   standard. Ordered by half-life, not by logical grouping. --- */
/* `label`, `window` and `why` are read by the DRIVER — the chip on each gap
   screen, the "Why now" card, and the fleet chase list — so they resolve
   through T() at access time. `half` and `ord` are the model and stay fixed:
   they decide the ordering, and an ordering that changed with the language
   would be a different product per language.

   A getter object rather than a function so every existing reader keeps
   working unchanged: PERISHABLE.witness.window still reads as a property, and
   tests/docs.mjs still enumerates the keys. */
const perishItem = (id, half, ord) => ({
  half, ord,
  get label() { return T('p_' + id + '_label'); },
  get window() { return T('p_' + id + '_window'); },
  get why() { return T('p_' + id + '_why'); },
});

